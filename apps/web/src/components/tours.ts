export type TourStep = { target?: string; title: string; text: string };
export type TourId = 'today' | 'plans' | 'food' | 'study' | 'gym' | 'budget' | 'books' | 'goal' | 'stats' | 'more' | 'profile' | 'settings';

export const TOUR_NAME: Record<TourId, string> = {
  today: 'Сегодня', plans: 'Планы', food: 'Еда', study: 'Учёба', gym: 'Зал', budget: 'Бюджет', books: 'Книги',
  goal: 'Цель', stats: 'Статистика', more: 'Ещё', profile: 'Профиль', settings: 'Настройки',
};
export const isTour = (tab: string): tab is TourId => tab in TOUR_NAME;

/** отметка «уже видел»: lumi.tour.<логин>.<страница> */
export const tourKey = (user: string, id: TourId) => `lumi.tour.${user}.${id}`;

